love.graphics.setDefaultFilter("nearest", "nearest")

function love.load()
    map = require ("/src/map")
    player = require ("/src/player")
    camera = require ("/libs/camera")
    cam = camera()
    gMap = map:New(grid,41,25)
    gPlayer = player:New( 256,256 ,64)
end


function love.update(dt)
    cam:lookAt(gPlayer.x, gPlayer.y)

    local w = love.graphics.getWidth()
    local h = love.graphics.getHeight()
    local mapWidth = gMap.width * gMap.cellsize
    local mapHeight = gMap.height * gMap.cellsize

    --Left and right boundaries
    if cam.x < w/2 then
        cam.x = w/2
    elseif cam.x > mapWidth - w/2 then
        cam.x = mapWidth - w/2
    end

    --Top and bottom boundaries
    if cam.y < h/2 then
        cam.y = h/2
    elseif cam.y > mapHeight - h/2 then
        cam.y = mapHeight - h/2
    end
    
end

function love.draw()
    cam:attach()
        gMap:Render()
        gPlayer:Render()
    cam:detach()
end

function love.keypressed(key)
        if key == "escape" then
            love.event.quit() 
        end
        if key == "z" then
            gPlayer:Move(gMap, 0, -1)
        elseif key == "s" then
            gPlayer:Move(gMap, 0, 1)
        elseif key == "q" then
            gPlayer:Move(gMap, -1, 0)
        elseif key == "d" then
            gPlayer:Move(gMap, 1, 0)
        end
end
